// Pack size in g/ml (null if unknown).
export function packSize(r) {
  const u = (r.unitOfMeasure || '').replace(/\s/g, '');
  const q = Number(r.quantity);
  if (!q) return null;
  // order matters: 'קילוגרם' contains 'גרם' and 'מיליליטר' contains 'ליטר'
  if (u.includes('מיליליטר')) return q;
  if (u.includes('קילוגרם') || u.includes('ליטר')) return q <= 5 ? q * 1000 : q;
  if (u.includes('גרם')) return q;
  return null;
}
